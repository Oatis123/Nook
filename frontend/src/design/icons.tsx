/* Themed icon set. Every icon the app uses is declared here once, as a lucide glyph
   plus per-skin replacements: GitHub renders Primer Octicons, Material renders
   Material Symbols (Rounded), Oatis renders 9×9 pixel icons (design/oatisIcons.ts), Pixel
   renders pixelarticons, Telegram keeps lucide with a heavier stroke, Anthropic keeps
   lucide as-is. Where a skin's set has no equivalent, lucide stands in.

   Import icons from '@/design/icons' rather than 'lucide-react' so they follow the
   active skin. The exports keep lucide's names so call sites read the same. */

export interface IconProps {
  size?: number
  /** Lucide stroke width, in its 24-unit viewBox. Ignored by filled icon sets. */
  strokeWidth?: number
  className?: string
  style?: CSSProperties
  'aria-label'?: string
}

export type AppIcon = ((props: IconProps) => JSX.Element) & { displayName?: string }

interface SkinVariants {
  github?: ComponentType<OcticonProps>
  /** Raw Material Symbols SVG source (viewBox 0 -960 960 960, single path). */
  material: string
  /** Raw pixelarticons SVG source (viewBox 0 0 24 24, one or more filled paths). */
  pixel: string
}

const LUCIDE_STROKE_SCALE: Record<ThemeSkin, number> = {
  oatis: 1.25,
  anthropic: 1,
  telegram: 1.25,
  github: 1.25,
  material: 1.25,
  pixel: 1.25,
}

function materialPath(svg: string): string {
  const match = /\sd="([^"]+)"/.exec(svg)
  if (!match) throw new Error('Material Symbol SVG without a path')
  return match[1]
}

function pixelPaths(svg: string): string[] {
  const paths = [...svg.matchAll(/\sd="([^"]+)"/g)].map((match) => match[1])
  if (paths.length === 0) throw new Error('pixelarticons SVG without a path')
  return paths
}

function themedIcon(name: string, Lucide: LucideIcon, variants: SkinVariants): AppIcon {
  const path = materialPath(variants.material)
  const pixel = pixelPaths(variants.pixel)
  const GithubIcon = variants.github
  const oatisName = OATIS_ICON_FOR[name]

  function Icon({ size = 24, strokeWidth = 2, className, style, ...aria }: IconProps) {
    const skin = useThemeStore((s) => s.skin)
    const a11y = aria['aria-label']
      ? { 'aria-label': aria['aria-label'], role: 'img' }
      : { 'aria-hidden': true as const }
    const classes = clsx('ui-icon shrink-0', className)

    if (skin === 'oatis' && oatisName) {
      // Pixel art only stays crisp at whole-number scales: 9, 18, 27px.
      const px = Math.max(1, Math.round(size / 9)) * 9
      return (
        <svg
          width={px}
          height={px}
          viewBox="0 0 9 9"
          fill="currentColor"
          shapeRendering="crispEdges"
          className={classes}
          style={style}
          {...a11y}
        >
          <path d={oatisIconPath(oatisName)} />
        </svg>
      )
    }
    if (skin === 'github' && GithubIcon) {
      return <GithubIcon size={size} className={classes} style={style} {...a11y} />
    }
    if (skin === 'material') {
      return (
        <svg
          width={size}
          height={size}
          viewBox="0 -960 960 960"
          fill="currentColor"
          className={classes}
          style={style}
          {...a11y}
        >
          <path d={path} />
        </svg>
      )
    }
    if (skin === 'pixel') {
      // crispEdges keeps the 24-unit grid sharp at sizes that aren't a multiple of 24,
      // instead of smearing each pixel's edge across two device pixels.
      return (
        <svg
          width={size}
          height={size}
          viewBox="0 0 24 24"
          fill="currentColor"
          shapeRendering="crispEdges"
          className={classes}
          style={style}
          {...a11y}
        >
          {pixel.map((d) => (
            <path key={d} d={d} />
          ))}
        </svg>
      )
    }
    return (
      <Lucide
        size={size}
        strokeWidth={strokeWidth * LUCIDE_STROKE_SCALE[skin]}
        className={classes}
        style={style}
        {...a11y}
      />
    )
  }
  Icon.displayName = name
  return Icon
}

