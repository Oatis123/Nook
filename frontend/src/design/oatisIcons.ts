const pathCache = new Map<string, string>()

/** SVG path (viewBox 0 0 9 9) covering the filled cells of a pixel icon. */
export function oatisIconPath(name: string): string {
  const cached = pathCache.get(name)
  if (cached !== undefined) return cached
  const rows = OATIS_BITMAPS[name].split('/')
  let path = ''
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      if (row[x] !== '#') {
        x++
        continue
      }
      const start = x
      while (x < row.length && row[x] === '#') x++
      path += `M${start} ${y}h${x - start}v1h-${x - start}z`
    }
  })
  pathCache.set(name, path)
  return path
}
